// Build step: turn source emails into paste-ready SendGrid templates.
//
// Why this exists: SendGrid dynamic templates do not support Handlebars
// partials, so a shared header/footer cannot be referenced at send time.
// We keep one copy of each shared module in src/partials/ and inline it
// here. Fixing the footer once fixes it in every email.
//
// Only `{{> name}}` markers are replaced. Every other Handlebars tag
// ({{first_name}}, {{#equals}} ...) is left untouched for SendGrid to render.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PARTIALS_DIR = path.join(ROOT, "src", "partials");
const EMAILS_DIR = path.join(ROOT, "src", "emails");
const OUT_DIR = path.join(ROOT, "templates");

const PARTIAL_TAG = /\{\{>\s*([\w-]+)\s*\}\}/g;

function loadPartial(name) {
  const file = path.join(PARTIALS_DIR, `${name}.html`);
  if (!fs.existsSync(file)) {
    // Fail loudly: a missing footer means a missing unsubscribe link.
    throw new Error(`Unknown partial "{{> ${name}}}" (expected ${file})`);
  }
  return fs.readFileSync(file, "utf8").trimEnd();
}

function inlinePartials(html) {
  return html.replace(PARTIAL_TAG, (_, name) => loadPartial(name));
}

fs.mkdirSync(OUT_DIR, { recursive: true });

for (const file of fs.readdirSync(EMAILS_DIR).filter((f) => f.endsWith(".html"))) {
  const source = fs.readFileSync(path.join(EMAILS_DIR, file), "utf8");
  const banner = `<!-- GENERATED by scripts/build.js from src/emails/${file}. Edit the source, not this file. -->`;
  const output = inlinePartials(source);

  // Any marker left over (e.g. a partial that includes another partial) is a bug.
  if (/\{\{>\s*[\w-]+\s*\}\}/.test(output)) {
    throw new Error(`${file}: unresolved partial tag after build`);
  }

  // Banner goes after the DOCTYPE: a comment before it can push some
  // clients into quirks mode.
  const withBanner = output.replace(/^(<!DOCTYPE[^>]*>)/i, `$1\n${banner}`);
  fs.writeFileSync(path.join(OUT_DIR, file), withBanner);
  console.log(`built templates/${file}`);
}
