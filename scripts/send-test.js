// Real (non-sandbox) test send of each template to OUR OWN verified inbox.
//
// Sandbox mode proves a request is valid, but it skips sender checks and
// never renders or delivers. This sends one real email per template so we
// can see SendGrid's own render in a real client, click the unsubscribe
// link, read the headers and see real events.
//
// Guard rail: the recipient is always SENDGRID_FROM_EMAIL (our verified
// sender). There is no flag to send anywhere else.
// Test sends carry the "qa_test" category and custom_arg so analytics can
// exclude them.
//
// Usage: npm run send-test

const fs = require("fs");
const path = require("path");
const { loadEnv, requireEnv, api, findDynamicTemplate, findAsmGroup } = require("./lib/sendgrid");
const { buildMailSendBody } = require("../src/service/build-mail");
const templates = require("../src/templates.config.json");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "docs", "evidence", "live-send.md");

// One segment per template, so the three emails show different branches.
const PLAN = {
  t1_welcome: "enterprise-finance.json",
  t2_account_type: "enterprise-finance.json",
  t3_industry: "startup-retail.json",
};

async function main() {
  loadEnv();
  requireEnv("SENDGRID_API_KEY", "SENDGRID_FROM_EMAIL");
  const ownInbox = process.env.SENDGRID_FROM_EMAIL;
  const asmGroupId = process.env.SENDGRID_ASM_GROUP_ONBOARDING || (await findAsmGroup("Onboarding"))?.id;

  const results = [];
  for (const t of templates) {
    const fixtureFile = PLAN[t.key];
    const signup = JSON.parse(fs.readFileSync(path.join(ROOT, "fixtures", fixtureFile), "utf8"));
    const templateId = (await findDynamicTemplate(t.name))?.id;

    const body = buildMailSendBody({ ...signup, email: ownInbox }, t, {
      templateId,
      asmGroupId,
      fromEmail: ownInbox,
      sandbox: false,
    });
    body.categories.push("qa_test");
    body.personalizations[0].custom_args.qa_test = "true";

    const res = await api("POST", "/mail/send", body);
    const errors = res.data && res.data.errors ? res.data.errors.map((e) => e.message).join("; ") : "";
    results.push({ key: t.key, fixture: fixtureFile.replace(".json", ""), status: res.status, messageId: res.messageId, errors });
    console.log(`${t.key} (${fixtureFile}): ${res.status} ${res.messageId || ""} ${errors}`);
  }

  const rows = results.map((r) => `| ${r.key} | ${r.fixture} | ${r.status} | \`${r.messageId || "-"}\` | ${r.errors} |`).join("\n");
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(
    OUT,
    `# Live test send: one real email per template

Generated by \`npm run send-test\` (scripts/send-test.js) on ${new Date().toISOString()}.

Sent with \`sandbox_mode\` off, from the account's verified Single Sender to the same inbox (address redacted here). Each message carries the \`qa_test\` category and custom_arg so reporting can exclude it.

| Template | Fixture | Status | X-Message-Id | Errors |
|---|---|---|---|---|
${rows}

\`202\` means SendGrid accepted the message for delivery. Delivery, opens and clicks are recorded from SendGrid's Email Activity and the inbox checks in docs/QA_CHECKLIST.md.
`
  );
  console.log(`\nWrote ${path.relative(ROOT, OUT)}`);
  if (results.some((r) => r.status !== 202)) process.exit(1);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
